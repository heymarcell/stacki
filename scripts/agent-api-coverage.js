// The coverage table, generated from the registry.
//
//   node scripts/agent-api-coverage.js          write docs/agent-api-coverage.md
//   node scripts/agent-api-coverage.js --check   fail if it is out of date
//
// The table is the answer to "was this considered", and a hand-written one
// answers it wrongly the first time somebody adds an operation. So it comes out
// of electron/mcp/agent/registry.js, which is also what the permission gate and
// get_capabilities read — three readers, one table, no way for the document to
// describe a surface that is not there.

const fs = require('node:fs');
const path = require('node:path');

const registry = require('../electron/mcp/agent/registry.js');

const OUT = path.join(__dirname, '..', 'docs', 'agent-api-coverage.md');

const RISK = {
  read: 'Inspect',
  write: 'Edit project',
  high: 'Full control',
};

const escape = (text) => String(text ?? '').replace(/\|/g, '\\|');

function render() {
  const lines = [];
  lines.push('# Agent API coverage');
  lines.push('');
  lines.push('<!-- Generated by scripts/agent-api-coverage.js from electron/mcp/agent/registry.js.');
  lines.push('     Do not edit by hand: `npm run agent:coverage` rewrites it, and the Agent API');
  lines.push('     test fails when it is out of date. -->');
  lines.push('');
  lines.push('Every project-semantic thing Stacki can do, and what an agent can do with it.');
  lines.push('The first table is the surface; the second is what is deliberately not on it,');
  lines.push('and why. A capability in neither table is an oversight, and `test/agent-api.js`');
  lines.push('says so.');
  lines.push('');
  lines.push('“Needs” is the lowest agent-access level that may run the operation — see');
  lines.push('[agent-api.md](agent-api.md) for what the levels mean.');
  lines.push('');

  for (const domain of registry.DOMAINS) {
    lines.push(`## ${domain}`);
    lines.push('');
    lines.push('| Action | Needs | Where | Undo | Reuses | What it does |');
    lines.push('| --- | --- | --- | --- | --- | --- |');
    for (const action of registry.actionsOf(domain)) {
      const op = registry.find(domain, action);
      lines.push(
        `| \`${action}\` | ${RISK[op.risk]} | ${op.via} | ${op.undoable ? '⌘Z' : '—'} | ${escape(op.reuses || op.channel || '—')} | ${escape(op.summary)} |`
      );
    }
    lines.push('');
  }

  lines.push('## Deliberately not exposed');
  lines.push('');
  lines.push('| Capability | Why | Reason |');
  lines.push('| --- | --- | --- |');
  for (const entry of registry.EXCLUDED) {
    lines.push(`| ${entry.channels.map((c) => `\`${c}\``).join('<br>')} | ${entry.why} | ${escape(entry.reason)} |`);
  }
  lines.push('');

  const all = registry.list();
  lines.push('## Totals');
  lines.push('');
  lines.push(`- ${registry.DOMAINS.length} domains, ${all.length} operations.`);
  lines.push(`- ${all.filter((op) => op.risk === 'read').length} readable in Inspect, ` +
    `${all.filter((op) => op.risk === 'write').length} more in Edit project, ` +
    `${all.filter((op) => op.risk === 'high').length} more in Full control.`);
  lines.push(`- ${all.filter((op) => op.undoable).length} land on Stacki's own undo stack.`);
  lines.push(`- ${registry.excludedChannels().size} capabilities deliberately kept out.`);
  lines.push('');
  return lines.join('\n');
}

const text = render();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== text) {
    console.error('docs/agent-api-coverage.md is out of date — run `npm run agent:coverage`.');
    process.exit(1);
  }
  console.log('agent-api-coverage: up to date');
  process.exit(0);
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, text, 'utf8');
console.log(`agent-api-coverage: wrote ${path.relative(path.join(__dirname, '..'), OUT)}`);
